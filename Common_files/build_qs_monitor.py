import io
import json
import os
from datetime import datetime, timezone

import boto3
import openpyxl
import yaml

CF_R2_ACCESS_KEY = os.getenv("CF_R2_ACCESS_KEY_ID")
CF_R2_SECRET_KEY = os.getenv("CF_R2_SECRET_ACCESS_KEY")
CF_R2_ENDPOINT_URL = os.getenv("CF_R2_ENDPOINT_URL")
BUCKET_NAME = os.getenv("CF_R2_BUCKET_NAME", "")

CLEAN_ENDPOINT = ""
if CF_R2_ENDPOINT_URL:
    CLEAN_ENDPOINT = CF_R2_ENDPOINT_URL.rstrip("/").removesuffix("/" + BUCKET_NAME)

# Categories where excel/ holds one file per manufacturer instead of one
# combined category file -- tracked as multiple "sheets" in monitor_stats.yml.
MULTI_FILE_CATEGORIES = {"cars_for_sale", "cars_for_rent"}
MAX_OBSERVED_DATES = 30

STATS_HEADER = (
    "# Auto-generated by Common_files/build_qs_monitor.py\n"
    "# Stored in Cloudflare R2 -- do not add to the repo.\n"
    "# Re-run the daily monitor workflow to refresh.\n\n"
)


def get_client():
    return boto3.client(
        "s3",
        endpoint_url=CLEAN_ENDPOINT,
        aws_access_key_id=CF_R2_ACCESS_KEY,
        aws_secret_access_key=CF_R2_SECRET_KEY,
        region_name="auto",
    )


def list_today_categories(client, dt: datetime) -> list:
    prefix = f"qatarsale/year={dt.year}/month={dt.strftime('%m')}/day={dt.strftime('%d')}/"
    paginator = client.get_paginator("list_objects_v2")
    categories = []
    for page in paginator.paginate(Bucket=BUCKET_NAME, Prefix=prefix, Delimiter="/"):
        for cp in page.get("CommonPrefixes", []):
            name = cp["Prefix"][len(prefix):].rstrip("/")
            if name:
                categories.append(name)
    return sorted(categories)


def read_json_key(client, key: str):
    try:
        obj = client.get_object(Bucket=BUCKET_NAME, Key=key)
        return json.loads(obj["Body"].read().decode("utf-8"))
    except client.exceptions.NoSuchKey:
        return None
    except Exception as e:
        print(f"  [WARN] could not read {key}: {e}")
        return None


def read_started_at(client, dt: datetime):
    key = f"qatarsale/monitor/year={dt.year}/month={dt.strftime('%m')}/day={dt.strftime('%d')}/_run_started_at.json"
    data = read_json_key(client, key)
    if not data:
        return None
    return datetime.fromisoformat(data["started_at"])


