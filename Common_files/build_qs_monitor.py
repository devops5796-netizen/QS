# monitor.json
# ---------------------------------------------------------------------------

def build_monitor_json(client, dt: datetime, categories: list) -> dict:
    cat_entries = []
    total_requests = 0
    total_failed = 0
    duration_sums_sec = 0.0

    for category in categories:
        base = f"qatarsale/year={dt.year}/month={dt.strftime('%m')}/day={dt.strftime('%d')}/{category}"

        summary = read_json_key(client, f"{base}/summary/summary.json")
        total_ads = summary.get("total_listings", 0) if summary else 0

        cat_entries.append({
            "name": category,
            "slug": category,
            "total_ads": total_ads,
        })

        metrics = read_json_key(client, f"{base}/summary/request_metrics.json")
        if metrics:
            total_requests += metrics.get("requests_total", 0)
            duration_sums_sec += metrics.get("duration_sec", 0) or 0

        failed = read_json_key(client, f"{base}/summary/failed.json")
        if failed:
            total_failed += failed.get("total_failed", 0)

    started_at = read_started_at(client, dt)
    duration_sec = round((dt - started_at).total_seconds(), 2) if started_at else round(duration_sums_sec, 2)

    error_rate_pct = round(total_failed / (total_requests + total_failed) * 100, 2) if (total_requests + total_failed) > 0 else 0
    requests_per_min = round(total_requests / (duration_sec / 60), 2) if duration_sec > 0 else total_requests

    return {
        "scraped_at": dt.isoformat(),
        "saved_to_s3_date": dt.strftime("%Y-%m-%d"),
        "total_categories": len(cat_entries),
        "total_ads": sum(c["total_ads"] for c in cat_entries),
        "categories": cat_entries,
        "request_metrics": {
            "requests_total": total_requests,
            "requests_failed": total_failed,
            "error_rate_pct": error_rate_pct,
            "requests_per_min": requests_per_min,
            "duration_sec": duration_sec,
        },
    }


